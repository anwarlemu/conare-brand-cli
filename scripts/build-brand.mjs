// brand/ -> build/: the files apps install and the docs site reads.
//   build/tokens.css   the brand's variables (light at :root, dark under [data-theme="dark"])
//   build/base.css     the base layer (body type, focus, selection)
//   build/fonts.css    @font-face for the vendored faces, served from <assetBase>/fonts/
//   build/brand.css    fonts + tokens + base in one file, what apps import
//   build/theme.css    the Tailwind 4 theme: tokens as utilities (bg-surface, text-fg, border-edge...)
//   build/tokens.json  every token, its value and its resolved value per theme
//   build/fonts/, build/textures/  the assets, copied as they are
// It also copies the assets into apps/www/public<assetBase>/ for the docs site.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brandDir = join(root, 'brand');
const out = join(root, 'build');
const brand = JSON.parse(readFileSync(join(brandDir, 'brand.json'), 'utf8'));
const tokensCss = readFileSync(join(brandDir, 'tokens.css'), 'utf8');
const baseCss = readFileSync(join(brandDir, 'base.css'), 'utf8');

/** The declarations of the first block whose selector is `selector`. */
export function block(css, selector) {
	const clean = css.replace(/\/\*[\s\S]*?\*\//g, '');
	const at = clean.indexOf(`${selector} {`);
	if (at < 0) return {};
	const body = clean.slice(clean.indexOf('{', at) + 1, clean.indexOf('}', at));
	const decls = {};
	for (const m of body.matchAll(/(--ds-[\w-]+)\s*:\s*([^;]+);/g)) decls[m[1]] = m[2].trim();
	return decls;
}

const light = block(tokensCss, ':root');
const dark = { ...light, ...block(tokensCss, '[data-theme="dark"]') };

/** A value with its var() references followed to the end. */
function resolve(value, table, depth = 0) {
	if (depth > 10) return value;
	return value.replace(/var\((--ds-[\w-]+)\)/g, (_, name) => (table[name] ? resolve(table[name], table, depth + 1) : `var(${name})`));
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(join(brandDir, 'fonts'), join(out, 'fonts'), { recursive: true });
cpSync(join(brandDir, 'textures'), join(out, 'textures'), { recursive: true });

const base = brand.assetBase ?? '/ds';
const fonts = brand.fonts.files
	.map((f) => `@font-face {\n  font-family: "${f.family}";\n  src: url("${base}/fonts/${f.file}") format("woff2");\n  font-weight: ${f.weight};\n  font-style: normal;\n  font-display: swap;\n}`)
	.join('\n');
const header = (what) => `/* ${brand.name} design system: ${what}. Generated by ${brand.bin} from brand/; do not edit. */\n`;

writeFileSync(join(out, 'tokens.css'), tokensCss);
writeFileSync(join(out, 'base.css'), baseCss);
writeFileSync(join(out, 'fonts.css'), `${header('fonts')}${fonts}\n`);
writeFileSync(join(out, 'brand.css'), `${header('fonts, tokens and base styles')}${fonts}\n\n${tokensCss}\n${baseCss}`);

// The Tailwind theme. `inline` so a utility reads the variable itself and a [data-theme] block
// switches it. Colors keep their token names: bg-surface, text-fg-muted, border-edge-strong,
// bg-action-primary, text-code-fg, bg-home-red.
const names = Object.keys(light);
const pick = (prefix) => names.filter((n) => n.startsWith(prefix));
const lines = [];
for (const n of pick('--ds-color-')) lines.push(`  --color-${n.slice('--ds-color-'.length)}: var(${n});`);
lines.push('  --font-sans: var(--ds-font-text);', '  --font-mono: var(--ds-font-code);');
for (const n of pick('--ds-font-').filter((n) => !n.includes('weight'))) lines.push(`  --font-${n.slice('--ds-font-'.length)}: var(${n});`);
for (const n of pick('--ds-font-weight-')) lines.push(`  --font-weight-${n.slice('--ds-font-weight-'.length)}: var(${n});`);
for (const n of pick('--ds-text-').filter((n) => !n.endsWith('-leading'))) {
	const step = n.slice('--ds-text-'.length);
	lines.push(`  --text-${step}: var(${n});`);
	if (light[`${n}-leading`]) lines.push(`  --text-${step}--line-height: var(${n}-leading);`);
}
for (const n of pick('--ds-tracking-')) lines.push(`  --tracking-${n.slice('--ds-tracking-'.length)}: var(${n});`);
for (const n of pick('--ds-radius-')) lines.push(`  --radius-${n.slice('--ds-radius-'.length)}: var(${n});`);
for (const n of pick('--ds-size-')) lines.push(`  --spacing-${n.slice('--ds-size-'.length)}: var(${n});`);
for (const n of pick('--ds-layout-')) lines.push(`  --container-${n.slice('--ds-layout-'.length)}: var(${n});`);
for (const n of pick('--ds-easing-')) lines.push(`  --ease-${n.slice('--ds-easing-'.length)}: var(${n});`);

// Composite type styles, as conare-web's type-* utilities, in the console's sizes.
const type = {
	display: ['heading', 'display', 'regular', 'display'],
	hero: ['heading', 'hero', 'regular', 'tight'],
	'heading-1': ['heading', 'heading-1', 'regular', 'tight'],
	'heading-2': ['heading', 'heading-2', 'regular', 'tight'],
	'heading-3': ['heading', 'heading-3', 'regular'],
	'heading-4': ['heading', 'heading-4', 'regular'],
	'body-lg': ['text', 'body-lg', 'regular'],
	body: ['text', 'body', 'regular'],
	ui: ['text', 'ui', 'regular'],
	'ui-strong': ['text', 'ui', 'medium'],
	meta: ['text', 'meta', 'regular'],
	caption: ['text', 'caption', 'regular'],
	tag: ['text', 'tag', 'medium', 'tag'],
	code: ['code', 'ui', 'regular'],
	'code-sm': ['code', 'meta', 'regular'],
};
const utilities = Object.entries(type).map(([name, [font, size, weight, tracking]]) => {
	const body = [
		`font-family: var(--ds-font-${font});`,
		`font-size: var(--ds-text-${size});`,
		`line-height: var(--ds-text-${size}-leading);`,
		`font-weight: var(--ds-font-weight-${weight});`,
		`letter-spacing: ${tracking ? `var(--ds-tracking-${tracking})` : '0'};`,
		...(name === 'tag' ? ['text-transform: uppercase;'] : []),
	];
	return `@utility type-${name} {\n  ${body.join('\n  ')}\n}`;
});

writeFileSync(
	join(out, 'theme.css'),
	`${header('the Tailwind 4 theme')}/* Import after @import "tailwindcss" and brand.css. */\n@theme inline {\n${lines.join('\n')}\n}\n\n${utilities.join('\n')}\n`,
);

const json = { name: brand.name, tokens: {} };
for (const n of names) json.tokens[n] = { value: light[n], light: resolve(light[n], light), dark: resolve(dark[n], dark) };
writeFileSync(join(out, 'tokens.json'), `${JSON.stringify(json, null, 2)}\n`);

// The docs site serves the assets at the same base an app does.
const www = join(root, 'apps', 'www', 'public', base.replace(/^\//, ''));
if (existsSync(join(root, 'apps', 'www'))) {
	rmSync(www, { recursive: true, force: true });
	mkdirSync(www, { recursive: true });
	cpSync(join(out, 'fonts'), join(www, 'fonts'), { recursive: true });
	cpSync(join(out, 'textures'), join(www, 'textures'), { recursive: true });
}
console.log(`build: ${names.length} tokens, ${brand.fonts.files.length} font files -> build/`);
