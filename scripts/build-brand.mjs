// brand/ -> build/: the files apps install and the docs site reads.
//   build/tokens.css   the brand's variables (light at :root, dark under [data-theme="dark"])
//   build/base.css     the base layer (body type, focus, selection)
//   build/fonts.css    @font-face for the vendored faces, served from <assetBase>/fonts/
//   build/brand.css    fonts + tokens + base in one file, what apps import
//   build/theme.css    the Tailwind 4 theme: tokens as utilities (bg-surface, text-fg, border-edge...)
//   build/tokens.json  every token, its value and its resolved value per theme
//   build/fonts/, build/textures/  the assets, copied as they are
// It also copies the assets into apps/www/public<assetBase>/ for the docs site.
import { createRequire } from 'node:module';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brandDir = join(root, 'brand');
const out = join(root, 'build');
const brand = JSON.parse(readFileSync(join(brandDir, 'brand.json'), 'utf8'));
const tokensCss = readFileSync(join(brandDir, 'tokens.css'), 'utf8');
const baseCss = readFileSync(join(brandDir, 'base.css'), 'utf8');
const fadeCss = readFileSync(join(brandDir, 'fade.css'), 'utf8');

/** The declarations of the first block whose selector is `selector`. */
export function block(css, selector) {
	const clean = css.replace(/\/\*[\s\S]*?\*\//g, '');
	const at = clean.indexOf(`${selector} {`);
	if (at < 0) return {};
	const body = clean.slice(clean.indexOf('{', at) + 1, clean.indexOf('}', at));
	const decls = {};
	for (const m of body.matchAll(/(--ds-[\w-]+)\s*:\s*([^;]+);/g)) decls[m[1]] = m[2].trim();
	return decls;
}

const light = block(tokensCss, ':root');
const dark = { ...light, ...block(tokensCss, '[data-theme="dark"]') };

/** A value with its var() references followed to the end. */
function resolve(value, table, depth = 0) {
	if (depth > 10) return value;
	return value.replace(/var\((--ds-[\w-]+)\)/g, (_, name) => (table[name] ? resolve(table[name], table, depth + 1) : `var(${name})`));
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(join(brandDir, 'fonts'), join(out, 'fonts'), { recursive: true });
cpSync(join(brandDir, 'textures'), join(out, 'textures'), { recursive: true });

const base = brand.assetBase ?? '/ds';
// The brand registers its faces under its own names ("Geist (Brand)"), and its font tokens name those first: an app
// that names the same family for its own text ("Inter") keeps its own rendering on pages the brand does not cover.
const own = (family) => `${family} (${brand.name})`;
const families = [...new Set(brand.fonts.files.map((f) => f.family))].sort((a, b) => b.length - a.length);
const tokensOut = tokensCss.replace(/^(\s*--ds-font-[\w-]+\s*:\s*)([^;]+);/gm, (line, head, stack) => {
	const first = families.find((f) => stack.trim().startsWith(`"${f}"`));
	return first ? `${head}"${own(first)}", ${stack.trim()};` : line;
});
const fonts = brand.fonts.files
	.map((f) => `@font-face {\n  font-family: "${own(f.family)}";\n  src: url("${base}/fonts/${f.file}") format("woff2");\n  font-weight: ${f.weight};\n  font-style: normal;\n  font-display: swap;\n}`)
	.join('\n');
const header = (what) => `/* ${brand.name} design system: ${what}. Generated by ${brand.bin} from brand/; do not edit. */\n`;

// The base layer scoped to the library's components (every root renders data-ds) and to what a selection restyled
// (.ds-scope): what a selection or a plain add installs, so the rest of the app keeps its own html, body and type.
// The outermost scoped element takes the body's type; inner ones inherit, as they would from the body. That rule uses
// :is, not :where: it must outrank Tailwind's preflight (button, input { font: inherit }) in the same base layer,
// and the layer keeps it under every utility class.
const scopedBase = `/* Scoped base: the brand's element defaults inside the library's components ([data-ds]) and the elements a
   selection restyled (.ds-scope) only. A whole-app apply installs the full base layer instead. */
@layer base {
  :is([data-ds], .ds-scope):not(:is([data-ds], .ds-scope) *) {
    color: var(--ds-color-fg);
    font-family: var(--ds-font-text);
    font-size: var(--ds-text-ui);
    line-height: var(--ds-text-ui-leading);
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
  }
  :where([data-ds], .ds-scope), :where([data-ds], .ds-scope) *, :where([data-ds], .ds-scope) ::before, :where([data-ds], .ds-scope) ::after, :where([data-ds], .ds-scope)::before, :where([data-ds], .ds-scope)::after {
    border-color: var(--ds-color-edge);
  }
  :where([data-ds], .ds-scope):focus-visible, :where([data-ds], .ds-scope) :focus-visible {
    outline: var(--ds-border-focus) solid var(--ds-color-edge-focus);
    outline-offset: var(--ds-border-focus);
  }
  :where([data-ds], .ds-scope)::selection, :where([data-ds], .ds-scope) ::selection {
    background: var(--ds-color-edge-accent);
    color: var(--ds-color-off-white);
  }
  :where([data-ds], .ds-scope) :where(a, button, [role="button"], [role="tab"]) {
    touch-action: manipulation;
  }
  @media (pointer: coarse), (max-width: 767px) {
    :is([data-ds], .ds-scope) :is(input:not([type="checkbox"], [type="radio"], [type="file"]), textarea, select) {
      font-size: var(--ds-text-input);
    }
  }
}
`;
writeFileSync(join(out, 'tokens.css'), tokensOut);
writeFileSync(join(out, 'base.css'), baseCss);
writeFileSync(join(out, 'base-scoped.css'), scopedBase);
writeFileSync(join(out, 'fonts.css'), `${header('fonts')}${fonts}\n`);
writeFileSync(join(out, 'fade.css'), fadeCss);
writeFileSync(join(out, 'brand.css'), `${header('fonts, tokens and base styles')}${fonts}\n\n${tokensOut}\n${baseCss}\n${fadeCss}`);
writeFileSync(join(out, 'brand-scoped.css'), `${header('fonts, tokens and the base scoped to its components')}${fonts}\n\n${tokensOut}\n${scopedBase}\n${fadeCss}`);

// The Tailwind theme. `inline` so a utility reads the variable itself and a [data-theme] block
// switches it. Colors keep their token names: bg-surface, text-fg-muted, border-edge-strong,
// bg-action-primary, text-code-fg, bg-home-red.
const names = Object.keys(light);
const pick = (prefix) => names.filter((n) => n.startsWith(prefix));
const lines = [];
// The brand's neutral primitives go as ds-neutral-*: Tailwind's own neutral-* scale stays as it is, so an app's
// text-neutral-700 keeps meaning Tailwind's dark grey wherever the brand has not been applied yet.
for (const n of pick('--ds-color-')) {
	const name = n.slice('--ds-color-'.length);
	lines.push(`  --color-${/^neutral-\d+$/.test(name) ? `ds-${name}` : name}: var(${n});`);
}
lines.push('  --font-sans: var(--ds-font-text);', '  --font-mono: var(--ds-font-code);');
for (const n of pick('--ds-font-').filter((n) => !n.includes('weight'))) lines.push(`  --font-${n.slice('--ds-font-'.length)}: var(${n});`);
for (const n of pick('--ds-font-weight-')) lines.push(`  --font-weight-${n.slice('--ds-font-weight-'.length)}: var(${n});`);
for (const n of pick('--ds-text-').filter((n) => !n.endsWith('-leading'))) {
	const step = n.slice('--ds-text-'.length);
	lines.push(`  --text-${step}: var(${n});`);
	if (light[`${n}-leading`]) lines.push(`  --text-${step}--line-height: var(${n}-leading);`);
}
for (const n of pick('--ds-tracking-')) lines.push(`  --tracking-${n.slice('--ds-tracking-'.length)}: var(${n});`);
// The brand kit's radius steps go as rounded-ds-sm...: Tailwind's own rounded-sm...xl keep their values, so an app's
// cards look as they did wherever the brand has not been applied yet (control, container and full keep their names).
for (const n of pick('--ds-radius-')) {
	const step = n.slice('--ds-radius-'.length);
	lines.push(`  --radius-${/^(sm|md|lg|xl)$/.test(step) ? `ds-${step}` : step}: var(${n});`);
}
for (const n of pick('--ds-size-')) lines.push(`  --spacing-${n.slice('--ds-size-'.length)}: var(${n});`);
for (const n of pick('--ds-layout-')) lines.push(`  --container-${n.slice('--ds-layout-'.length)}: var(${n});`);
for (const n of pick('--ds-easing-')) lines.push(`  --ease-${n.slice('--ds-easing-'.length)}: var(${n});`);

// Composite type styles, as conare-web's type-* utilities, in the console's sizes.
const type = {
	display: ['heading', 'display', 'regular', 'display'],
	hero: ['heading', 'hero', 'regular', 'tight'],
	'heading-1': ['heading', 'heading-1', 'regular', 'tight'],
	'heading-2': ['heading', 'heading-2', 'regular', 'tight'],
	'heading-3': ['heading', 'heading-3', 'regular'],
	'heading-4': ['heading', 'heading-4', 'regular'],
	'body-lg': ['text', 'body-lg', 'regular'],
	body: ['text', 'body', 'regular'],
	ui: ['text', 'ui', 'regular'],
	'ui-strong': ['text', 'ui', 'medium'],
	meta: ['text', 'meta', 'regular'],
	caption: ['text', 'caption', 'regular'],
	tag: ['text', 'tag', 'medium', 'tag'],
	code: ['code', 'ui', 'regular'],
	'code-sm': ['code', 'meta', 'regular'],
};
const utilities = Object.entries(type).map(([name, [font, size, weight, tracking]]) => {
	const body = [
		`font-family: var(--ds-font-${font});`,
		`font-size: var(--ds-text-${size});`,
		`line-height: var(--ds-text-${size}-leading);`,
		`font-weight: var(--ds-font-weight-${weight});`,
		`letter-spacing: ${tracking ? `var(--ds-tracking-${tracking})` : '0'};`,
		...(name === 'tag' ? ['text-transform: uppercase;'] : []),
	];
	return `@utility type-${name} {\n  ${body.join('\n  ')}\n}`;
});

// Scroll edges fade, never cut content off: fade-y on a list that scrolls down, fade-x on a line that scrolls sideways.
// The first mask layer is the fade over the box's inside, reading --fade-start and --fade-end, which scroll-driven
// animations (brand/fade.css, in brand.css) grow over the first and last 24px of scroll: no fade at an edge with
// nothing past it, none when nothing scrolls. Browsers without scroll timelines get a short fixed fade. The other two
// layers keep everything outside the padding box whole (a border, an outline, a shadow, a popover that leaves the box):
// only the scrolled content fades. A scroller with the keyboard focus drops the mask so its whole ring shows. The mask
// color only needs to be opaque.
const opaque = 'var(--ds-color-off-black)';
const fades = [
	['y', 'bottom', 'block'],
	['x', 'right', 'inline'],
].map(([axis, to, scroll]) =>
	[
		`@utility fade-${axis} {`,
		`  mask-image: linear-gradient(to ${to}, transparent, ${opaque} var(--fade-start), ${opaque} calc(100% - var(--fade-end)), transparent), linear-gradient(${opaque} 0 0), linear-gradient(${opaque} 0 0);`,
		'  mask-clip: padding-box, border-box, padding-box;',
		'  mask-clip: padding-box, no-clip, padding-box;',
		'  mask-composite: add, exclude, add;',
		'  @supports (animation-timeline: scroll()) {',
		'    animation: fade-start linear both, fade-end linear both;',
		`    animation-timeline: scroll(self ${scroll}), scroll(self ${scroll});`,
		'    animation-range: 0px 24px, calc(100% - 24px) 100%;',
		'  }',
		'  @supports not (animation-timeline: scroll()) {',
		'    --fade-start: 8px;',
		'    --fade-end: 8px;',
		'  }',
		'  &:focus-visible { mask-image: none; }',
		'}',
	].join('\n'),
);

// Both axes: the vertical and the sideways fade intersect, and the space outside the padding box stays whole as above
// (layers from the top: outside, inside, down, across; outside xor (inside minus both fades) leaves the fades inside).
const both = (to, start, end) => `linear-gradient(to ${to}, transparent, ${opaque} var(${start}), ${opaque} calc(100% - var(${end})), transparent)`;
fades.push(
	[
		'@utility fade-xy {',
		`  mask-image: linear-gradient(${opaque} 0 0), linear-gradient(${opaque} 0 0), ${both('bottom', '--fade-start', '--fade-end')}, ${both('right', '--fade-x-start', '--fade-x-end')};`,
		'  mask-clip: border-box, padding-box, padding-box, padding-box;',
		'  mask-clip: no-clip, padding-box, padding-box, padding-box;',
		'  mask-composite: exclude, subtract, intersect, add;',
		'  @supports (animation-timeline: scroll()) {',
		'    animation: fade-start linear both, fade-end linear both, fade-x-start linear both, fade-x-end linear both;',
		'    animation-timeline: scroll(self block), scroll(self block), scroll(self inline), scroll(self inline);',
		'    animation-range: 0px 24px, calc(100% - 24px) 100%, 0px 24px, calc(100% - 24px) 100%;',
		'  }',
		'  @supports not (animation-timeline: scroll()) {',
		'    --fade-start: 8px;',
		'    --fade-end: 8px;',
		'    --fade-x-start: 8px;',
		'    --fade-x-end: 8px;',
		'  }',
		'  &:focus-visible { mask-image: none; }',
		'}',
	].join('\n'),
);

writeFileSync(
	join(out, 'theme.css'),
	`${header('the Tailwind 4 theme')}/* Import after @import "tailwindcss" and brand.css. */\n@theme inline {\n${lines.join('\n')}\n}\n\n${utilities.join('\n')}\n${fades.join('\n')}\n`,
);

const json = { name: brand.name, tokens: {} };
for (const n of names) json.tokens[n] = { value: light[n], light: resolve(light[n], light), dark: resolve(dark[n], dark) };
writeFileSync(join(out, 'tokens.json'), `${JSON.stringify(json, null, 2)}\n`);

// The docs site serves the assets at the same base an app does.
const www = join(root, 'apps', 'www', 'public', base.replace(/^\//, ''));
if (existsSync(join(root, 'apps', 'www'))) {
	rmSync(www, { recursive: true, force: true });
	mkdirSync(www, { recursive: true });
	cpSync(join(out, 'fonts'), join(www, 'fonts'), { recursive: true });
	cpSync(join(out, 'textures'), join(www, 'textures'), { recursive: true });
	cpSync(join(brandDir, 'logo'), join(www, 'logo'), { recursive: true });
	cpSync(join(brandDir, 'logo', 'favicon', 'favicon.ico'), join(root, 'apps', 'www', 'public', 'favicon.ico'));
	cpSync(join(brandDir, 'logo', 'favicon', 'apple-touch-icon.png'), join(root, 'apps', 'www', 'public', 'apple-touch-icon.png'));
}
console.log(`build: ${names.length} tokens, ${brand.fonts.files.length} font files -> build/`);

// Which characters each face can draw (build/glyphs.json): the image engines refuse copy a face would drop.
{
	const require = createRequire(import.meta.url);
	const opentype = require('opentype.js');
	const { decompress } = require('wawoff2');
	const glyphs = {};
	for (const f of brand.fonts.files) {
		const ttf = Buffer.from(await decompress(readFileSync(join(brandDir, 'fonts', f.file))));
		const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));
		const codes = Object.keys(font.tables.cmap.glyphIndexMap).map(Number).sort((a, b) => a - b);
		const ranges = [];
		for (const c of codes) {
			const last = ranges[ranges.length - 1];
			if (last && c === last[1] + 1) last[1] = c;
			else ranges.push([c, c]);
		}
		glyphs[f.file] = ranges;
	}
	writeFileSync(join(out, 'glyphs.json'), JSON.stringify(glyphs));
}
